# ============================================================
# JOB SALARY PREDICTION
# DATA CLEANING AND PREPROCESSING
# ============================================================

# ------------------------------------------------------------
# 1. IMPORT LIBRARIES
# ------------------------------------------------------------

import pandas as pd
import numpy as np

from sklearn.model_selection import train_test_split
from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder


# ------------------------------------------------------------
# 2. LOAD DATASET
# ------------------------------------------------------------

file_path = "/content/job_salary_prediction_dataset.csv"

df = pd.read_csv(file_path)

print("=" * 60)
print("DATASET LOADED")
print("=" * 60)

print("Number of rows    :", df.shape[0])
print("Number of columns :", df.shape[1])


# ------------------------------------------------------------
# 3. DISPLAY ORIGINAL DATA
# ------------------------------------------------------------

print("\nFirst 5 rows of original dataset:")
display(df.head())


# ------------------------------------------------------------
# 4. CHECK COLUMN NAMES
# ------------------------------------------------------------

print("\nColumn names:")
print(df.columns.tolist())


# ------------------------------------------------------------
# 5. CHECK DATA TYPES
# ------------------------------------------------------------

print("\n" + "=" * 60)
print("DATA TYPES")
print("=" * 60)

print(df.dtypes)


# ------------------------------------------------------------
# 6. CHECK MISSING VALUES
# ------------------------------------------------------------

print("\n" + "=" * 60)
print("MISSING VALUE CHECK")
print("=" * 60)

missing_values = df.isnull().sum()

print(missing_values)

total_missing = missing_values.sum()

print("\nTotal missing values:", total_missing)


# ------------------------------------------------------------
# 7. HANDLE MISSING VALUES
# ------------------------------------------------------------

if total_missing > 0:

    print("\nMissing values found.")

    # Numerical columns
    numerical_columns = df.select_dtypes(
        include=np.number
    ).columns

    for column in numerical_columns:
        if df[column].isnull().sum() > 0:
            df[column] = df[column].fillna(
                df[column].median()
            )

    # Categorical columns
    categorical_columns = df.select_dtypes(
        include="object"
    ).columns

    for column in categorical_columns:
        if df[column].isnull().sum() > 0:
            df[column] = df[column].fillna(
                df[column].mode()[0]
            )

    print("Missing values handled.")

else:

    print("\nNo missing values found.")
    print("No missing-value treatment required.")


# ------------------------------------------------------------
# 8. CHECK DUPLICATE ROWS
# ------------------------------------------------------------

print("\n" + "=" * 60)
print("DUPLICATE CHECK")
print("=" * 60)

duplicate_count = df.duplicated().sum()

print("Duplicate rows:", duplicate_count)


# ------------------------------------------------------------
# 9. REMOVE DUPLICATES IF PRESENT
# ------------------------------------------------------------

if duplicate_count > 0:

    df = df.drop_duplicates()

    print(
        "Duplicate rows removed."
    )

else:

    print(
        "No duplicate rows found."
    )


# ------------------------------------------------------------
# 10. CHECK FOR DUPLICATE IDs
# ------------------------------------------------------------

if "id" in df.columns:

    duplicate_ids = df["id"].duplicated().sum()

    print("\nDuplicate IDs:", duplicate_ids)

    if duplicate_ids > 0:

        df = df.drop_duplicates(
            subset=["id"]
        )

        print("Duplicate IDs removed.")

    else:

        print("No duplicate IDs found.")


# ------------------------------------------------------------
# 11. CHECK TARGET VARIABLE
# ------------------------------------------------------------

print("\n" + "=" * 60)
print("TARGET VARIABLE CHECK")
print("=" * 60)

print("Target variable: salary")

print("\nSalary data type:")
print(df["salary"].dtype)

print("\nSalary statistics:")
print(df["salary"].describe())


# ------------------------------------------------------------
# 12. CHECK INVALID SALARY VALUES
# ------------------------------------------------------------

negative_salary = (df["salary"] < 0).sum()

print("\nNegative salary values:", negative_salary)

if negative_salary > 0:

    df = df[df["salary"] >= 0]

    print("Invalid negative salary rows removed.")

else:

    print("No invalid negative salary values found.")


# ------------------------------------------------------------
# 13. CHECK FINAL DATASET
# ------------------------------------------------------------

print("\n" + "=" * 60)
print("CLEANED DATASET")
print("=" * 60)

print("Rows    :", df.shape[0])
print("Columns :", df.shape[1])

print("\nMissing values after cleaning:")
print(df.isnull().sum())

print("\nDuplicates after cleaning:")
print(df.duplicated().sum())


# ------------------------------------------------------------
# 14. SEPARATE FEATURES AND TARGET
# ------------------------------------------------------------

X = df.drop(
    "salary",
    axis=1
)

y = df["salary"]


print("\n" + "=" * 60)
print("FEATURE / TARGET SEPARATION")
print("=" * 60)

print("\nInput features:")
print(X.columns.tolist())

print("\nTarget:")
print("salary")


# ------------------------------------------------------------
# 15. DEFINE CATEGORICAL FEATURES
# ------------------------------------------------------------

categorical_features = [
    "job_title",
    "education_level",
    "industry",
    "company_size",
    "location",
    "remote_work"
]


# ------------------------------------------------------------
# 16. DEFINE NUMERICAL FEATURES
# ------------------------------------------------------------

numerical_features = [
    "experience_years",
    "skills_count",
    "certifications"
]


print("\nCategorical features:")
print(categorical_features)

print("\nNumerical features:")
print(numerical_features)


# ------------------------------------------------------------
# 17. TRAIN-TEST SPLIT
# ------------------------------------------------------------

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42
)


print("\n" + "=" * 60)
print("TRAIN-TEST SPLIT")
print("=" * 60)

print("Total samples    :", len(X))

print("Training samples :", len(X_train))

print("Testing samples  :", len(X_test))


# ------------------------------------------------------------
# 18. ONE-HOT ENCODING
# ------------------------------------------------------------

preprocessor = ColumnTransformer(
    transformers=[
        (
            "categorical",
            OneHotEncoder(
                handle_unknown="ignore"
            ),
            categorical_features
        )
    ],
    remainder="passthrough"
)


# ------------------------------------------------------------
# 19. FIT PREPROCESSOR ONLY ON TRAINING DATA
# ------------------------------------------------------------

X_train_processed = preprocessor.fit_transform(
    X_train
)

X_test_processed = preprocessor.transform(
    X_test
)


# ------------------------------------------------------------
# 20. DISPLAY PREPROCESSED DATA INFORMATION
# ------------------------------------------------------------

print("\n" + "=" * 60)
print("PREPROCESSING OUTPUT")
print("=" * 60)

print(
    "Original training features :",
    X_train.shape[1]
)

print(
    "Processed training features:",
    X_train_processed.shape[1]
)

print(
    "Original testing features  :",
    X_test.shape[1]
)

print(
    "Processed testing features :",
    X_test_processed.shape[1]
)


# ------------------------------------------------------------
# 21. DISPLAY FINAL TARGET DATA
# ------------------------------------------------------------

print("\nFirst 10 target values:")
print(y_train.head(10))


# ------------------------------------------------------------
# 22. SAVE CLEANED DATASET
# ------------------------------------------------------------

cleaned_file = "/content/cleaned_job_salary_dataset.csv"

df.to_csv(
    cleaned_file,
    index=False
)

print("\n" + "=" * 60)
print("CLEANED DATASET SAVED")
print("=" * 60)

print(cleaned_file)


# ------------------------------------------------------------
# 23. SAVE PREPROCESSOR
# ------------------------------------------------------------

import joblib

preprocessor_file = "/content/salary_preprocessor.pkl"

joblib.dump(
    preprocessor,
    preprocessor_file
)

print("\nPreprocessor saved as:")
print(preprocessor_file)


# ------------------------------------------------------------
# 24. FINAL SUMMARY
# ------------------------------------------------------------

print("\n" + "=" * 60)
print("FINAL PREPROCESSING SUMMARY")
print("=" * 60)

print("Original dataset size      : 250000 rows × 10 columns")
print("Missing values             :", df.isnull().sum().sum())
print("Duplicate rows             :", df.duplicated().sum())
print("Training samples           :", len(X_train))
print("Testing samples            :", len(X_test))
print("Categorical encoding       : One-Hot Encoding")
print("Numerical features         : Kept as numerical")
print("Train/Test ratio           : 80/20")

print("\nPreprocessing completed successfully!")